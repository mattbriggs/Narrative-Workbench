// build-tokens.mjs
// Emit CSS custom properties from the DTCG token file (the single source of
// visual values, spec SS4). Role tokens map by replacing dots with hyphens and
// adding the `--` prefix, e.g. {color.role.text-primary} -> --color-role-text-primary.
// Typography role tokens expand into component properties.
//
// Usage: node design-tokens/build-tokens.mjs [tokensPath] [outPath]
// Exits non-zero if any alias cannot be resolved.

import { readFileSync, writeFileSync } from "node:fs";

const tokensPath = process.argv[2] ?? new URL("./tokens.dtcg.json", import.meta.url).pathname;
const outPath = process.argv[3] ?? new URL("../app/ui/styles/css-variables.css", import.meta.url).pathname;

const doc = JSON.parse(readFileSync(tokensPath, "utf8"));

/** Resolve a DTCG node by dotted path to its raw $value (following one level). */
function nodeAt(path) {
  return path.split(".").reduce((acc, k) => (acc == null ? acc : acc[k]), doc);
}

const unresolved = [];

/** Resolve an alias string like "{color.base.white}" to a concrete $value, recursively. */
function resolveValue(value, trail = new Set()) {
  if (typeof value === "string") {
    const m = value.match(/^\{([^}]+)\}$/);
    if (m) {
      const ref = m[1];
      if (trail.has(ref)) { unresolved.push(ref); return null; }
      const target = nodeAt(ref);
      if (!target || !("$value" in target)) { unresolved.push(ref); return null; }
      return resolveValue(target.$value, new Set(trail).add(ref));
    }
    return value;
  }
  return value;
}

/** Format a resolved $value as a CSS value. */
function formatCss(v) {
  if (v == null) return null;
  if (Array.isArray(v)) return v.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(", ");
  if (typeof v === "object" && "value" in v && "unit" in v) return `${v.value}${v.unit}`;
  return String(v);
}

const lines = [];
lines.push("/* GENERATED by design-tokens/build-tokens.mjs. Do not edit. */");
lines.push(":root {");

/** Walk a DTCG subtree emitting a CSS var per leaf (a node carrying $value). */
function walk(node, pathParts) {
  if (node && typeof node === "object" && "$value" in node) {
    const varName = "--" + pathParts.join("-");
    const resolved = resolveValue(node.$value);
    if (typeof resolved === "object" && resolved !== null && !Array.isArray(resolved) && !("value" in resolved)) {
      // Typography composite: expand into sub-properties.
      for (const [prop, pv] of Object.entries(resolved)) {
        const r = resolveValue(pv);
        const css = formatCss(r);
        if (css !== null) lines.push(`  ${varName}-${camelToKebab(prop)}: ${css};`);
      }
    } else {
      const css = formatCss(resolved);
      if (css !== null) lines.push(`  ${varName}: ${css};`);
    }
    return;
  }
  if (node && typeof node === "object") {
    for (const [k, v] of Object.entries(node)) {
      if (k.startsWith("$")) continue;
      walk(v, [...pathParts, k]);
    }
  }
}

function camelToKebab(s) {
  return s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());
}

for (const [group, node] of Object.entries(doc)) {
  if (group.startsWith("$")) continue;
  walk(node, [group]);
}

lines.push("}");

if (unresolved.length) {
  console.error(`Unresolved aliases: ${[...new Set(unresolved)].join(", ")}`);
  process.exit(1);
}

writeFileSync(outPath, lines.join("\n") + "\n");
console.log(`Wrote ${outPath} (${lines.length - 3} custom properties, 0 unresolved aliases).`);
